def run(context):
    ui = None
    log = []
    try:
        app = adsk.core.Application.get()
        ui = app.userInterface

        # A fresh document, so re-running never merges into existing geometry.
        doc = app.documents.add(
            adsk.core.DocumentTypes.FusionDesignDocumentType)
        design = adsk.fusion.Design.cast(app.activeProduct)
        design.designType = adsk.fusion.DesignTypes.ParametricDesignType
        root = design.rootComponent
        try:
            root.name = 'RotorAssembly'
        except Exception:
            pass

        cfg = CONFIG
        add_user_parameters(design, cfg, log)

        blade = build_blade(root, cfg, log)

        # Blades 2..n: same component, rotated about the rotor (Y) axis, with
        # precone applied as a tilt about the chordwise axis. Re-using the one
        # component rather than rebuilding means editing the blade updates all
        # three -- which is the point of an assembly.
        yaxis = adsk.core.Vector3D.create(0, 1, 0)
        xaxis = adsk.core.Vector3D.create(1, 0, 0)
        origin = adsk.core.Point3D.create(0, 0, 0)
        precone = math.radians(cfg['precone_deg'])

        cone = adsk.core.Matrix3D.create()
        cone.setToRotation(precone, xaxis, origin)
        root.occurrences.item(0).transform = cone

        for k in range(1, cfg['n_blades']):
            m = adsk.core.Matrix3D.create()
            m.setToRotation(2.0 * math.pi * k / cfg['n_blades'], yaxis, origin)
            m.transformBy(cone)
            root.occurrences.addExistingComponent(blade, m)
        log.append('%d blade occurrences placed, precone %.1f deg.'
                   % (cfg['n_blades'], cfg['precone_deg']))

        if cfg['build_hub']:
            build_hub(root, cfg, log)
        if cfg['build_spinner']:
            build_spinner(root, cfg, log)
        if cfg['build_root_bolts']:
            build_root_bolts(root, cfg, log)

        # Report planform so the numbers can be checked against the BOM
        # without measuring the model.
        log.append('')
        log.append('Planform check (r/R, chord m, twist deg, t/c, prebend m):')
        for rR in (0.0, 0.1, 0.22, 0.5, 0.75, 1.0):
            log.append('  %.2f   %6.3f   %5.2f   %5.3f   %5.3f'
                       % (rR, chord_at(rR, cfg), twist_at(rR, cfg),
                          thickness_at(rR, cfg), prebend_at(rR, cfg)))

        app.activeViewport.fit()
        ui.messageBox('Rotor assembly built.\n\n' + '\n'.join(log),
                      'WindTurbineBlade')

    except Exception:
        msg = 'WindTurbineBlade failed:\n\n%s' % traceback.format_exc()
        if log:
            msg += '\n\nCompleted before the failure:\n' + '\n'.join(log)
        if ui:
            ui.messageBox(msg, 'WindTurbineBlade')
        else:
            print(msg)
