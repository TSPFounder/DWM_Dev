# PURE GEOMETRY -- no Fusion dependency, unit-testable outside Fusion
# =============================================================================

def naca4_thickness(x, t):
    """NACA 4-digit half-thickness distribution at chordwise fraction x.

    The -0.1015 final coefficient is the ORIGINAL (open trailing edge) form.
    That is deliberate: it leaves a small blunt trailing edge, which is both
    what thick wind-turbine sections actually have and what lets the profile
    close with a straight TE segment instead of a cusp. A cusped TE lofts
    badly -- Fusion tends to produce a sliver face or fail outright.
    """
    return 5.0 * t * (0.2969 * math.sqrt(x)
                      - 0.1260 * x
                      - 0.3516 * x ** 2
                      + 0.2843 * x ** 3
                      - 0.1015 * x ** 4)


def naca4_camber(x, m, p):
    """Return (camber y, camber slope dy/dx) for the NACA 4-digit mean line."""
    if m <= 0.0 or p <= 0.0:
        return 0.0, 0.0
    if x < p:
        y = (m / p ** 2) * (2.0 * p * x - x ** 2)
        dy = (2.0 * m / p ** 2) * (p - x)
    else:
        y = (m / (1.0 - p) ** 2) * ((1.0 - 2.0 * p) + 2.0 * p * x - x ** 2)
        dy = (2.0 * m / (1.0 - p) ** 2) * (p - x)
    return y, dy


def cosine_spacing(n):
    """Chordwise stations clustered at leading and trailing edge.

    Uniform spacing under-resolves the leading edge, where curvature is
    highest; the loft then shows visible faceting there. Cosine spacing costs
    nothing and fixes it.
    """
    return [0.5 * (1.0 - math.cos(math.pi * i / (n - 1))) for i in range(n)]


def airfoil_section(tc, n_pts, camber_m, camber_p):
    """Normalised airfoil contour for a given thickness-to-chord ratio.

    Returns a list of (x, y) in chord-normalised coordinates, ordered from the
    upper trailing edge, forward over the nose, and back along the lower
    surface to the lower trailing edge. The contour is deliberately left OPEN
    at the trailing edge -- the caller closes it with a straight segment.

    REPLACE THIS FUNCTION to use real tabulated sections (DU 00-W-401,
    NACA 64-618, ...). Nothing downstream depends on how the points are
    produced, only on the ordering and normalisation described above.
    """
    xs = cosine_spacing(n_pts)

    upper, lower = [], []
    for x in xs:
        yt = naca4_thickness(x, tc)
        yc, dyc = naca4_camber(x, camber_m, camber_p)
        theta = math.atan(dyc)
        upper.append((x - yt * math.sin(theta), yc + yt * math.cos(theta)))
        lower.append((x + yt * math.sin(theta), yc - yt * math.cos(theta)))

    # upper TE -> LE, then LE -> lower TE, without repeating the nose point
    return list(reversed(upper)) + lower[1:]


def circle_section(n_pts):
    """Root circle, sampled with the SAME parameterisation as the airfoil.

    Matching the point ordering and count is what makes the blend in
    blended_section() a simple element-wise interpolation. A circle sampled by
    equal angle instead would pair the wrong points together and the morph
    would twist through the transition region.
    """
    xs = cosine_spacing(n_pts)
    r = 0.5

    def y_of(x):
        d = r ** 2 - (x - 0.5) ** 2
        return math.sqrt(d) if d > 0.0 else 0.0

    upper = [(x, y_of(x)) for x in xs]
    lower = [(x, -y_of(x)) for x in xs]
    return list(reversed(upper)) + lower[1:]


def smoothstep(a, b, x):
    """Hermite blend, 0 below a and 1 above b, with zero slope at both ends.

    Zero slope matters here: a linear blend produces a visible crease in the
    lofted surface where the transition starts and stops.
    """
    if b <= a:
        return 0.0 if x < a else 1.0
    t = min(1.0, max(0.0, (x - a) / (b - a)))
    return t * t * (3.0 - 2.0 * t)


def chord_at(rR, cfg):
    """Chord [m] at span fraction rR, in three pieces.

    Root -> max chord is a smooth rise; max chord -> tip is a near-linear
    taper. Real blades are defined by a table, not a formula; this reproduces
    the three planform numbers the BOM actually gives (root diameter, max
    chord and station, tip chord) and interpolates smoothly between them.
    """
    root_c = cfg['root_diameter_m']
    peak_c = cfg['max_chord_m']
    tip_c = cfg['tip_chord_m']
    peak_r = cfg['max_chord_station']

    if rR <= peak_r:
        return root_c + (peak_c - root_c) * smoothstep(0.0, peak_r, rR)

    # Linear outboard taper. An earlier version used t**0.85 here, which is
    # wrong in a way that is easy to miss: d/dt of t^0.85 is 0.85*t^-0.15,
    # which is INFINITE at t = 0. The chord therefore arrived at max chord
    # with zero slope and left it with infinite slope -- a derivative
    # singularity right at the shoulder, which pinches the loft. Any exponent
    # < 1 has this problem. Linear keeps the slope finite, and a near-linear
    # outboard taper is how blade planforms are normally tabulated anyway.
    #
    # There is still a finite slope DISCONTINUITY at peak_r. That is a real
    # planform feature -- blades do have a distinct max-chord shoulder -- not
    # a numerical artefact.
    t = (rR - peak_r) / (1.0 - peak_r)
    return peak_c + (tip_c - peak_c) * t


def twist_at(rR, cfg):
    """Twist [deg], washout from root to tip.

    Maximum inboard where the local inflow angle is steepest, decaying to
    ~0 at the tip. The exponent shapes how fast it unwinds.
    """
    return cfg['twist_total_deg'] * (1.0 - rR) ** 1.6


def thickness_at(rR, cfg):
    """Thickness-to-chord ratio, from a circular root to a thin tip."""
    blend = smoothstep(cfg['circle_blend_start'], cfg['circle_blend_end'], rR)
    inboard = cfg['tc_root'] + (cfg['tc_inboard'] - cfg['tc_root']) * blend
    if rR <= cfg['circle_blend_end']:
        return inboard
    t = (rR - cfg['circle_blend_end']) / (1.0 - cfg['circle_blend_end'])
    return cfg['tc_inboard'] + (cfg['tc_tip'] - cfg['tc_inboard']) * t


def prebend_at(rR, cfg):
    """Out-of-plane prebend [m].

    Cubic in span so both displacement and slope are zero at the root, which
    is what a cantilever pre-deflection actually looks like. The BOM gives the
    tip value; the shape is the standard assumption.
    """
    return cfg['prebend_tip_m'] * (rR ** 3)


def blended_section(rR, cfg):
    """Normalised contour at span fraction rR: circle, airfoil, or a morph."""
    n = cfg['n_airfoil_points']
    tc = thickness_at(rR, cfg)
    w = smoothstep(cfg['circle_blend_start'], cfg['circle_blend_end'], rR)

    if w <= 0.0:
        return circle_section(n)
    if w >= 1.0:
        return airfoil_section(tc, n, cfg['camber_frac'], cfg['camber_pos'])

    circ = circle_section(n)
    foil = airfoil_section(tc, n, cfg['camber_frac'], cfg['camber_pos'])
    return [(c[0] + (f[0] - c[0]) * w, c[1] + (f[1] - c[1]) * w)
            for c, f in zip(circ, foil)]


def apply_twist_prebend(pts_local_m, rR, cfg):
    """Rotate about the pitch axis by the local twist, then offset by prebend.

    Split out from the section builders so that the aeroshell and the internal
    structure provably share ONE transform. When each built its own, a change
    to the twist convention could silently move the skin and not the spar --
    which is exactly the class of error the containment test now catches.
    """
    tw = math.radians(twist_at(rR, cfg))
    yb = prebend_at(rR, cfg)
    ct, st = math.cos(tw), math.sin(tw)
    return [(x * ct - y * st, x * st + y * ct + yb) for (x, y) in pts_local_m]


def station_points_local(rR, cfg):
    """Blade contour at rR in the UNTWISTED section frame, METRES.

    Origin is the pitch axis, X chordwise, Y out-of-plane.
    """
    c = chord_at(rR, cfg)
    ax = cfg['pitch_axis_frac']
    return [((xn - ax) * c, yn * c) for (xn, yn) in blended_section(rR, cfg)]


def station_points(rR, cfg):
    """Blade contour at span fraction rR, in blade coordinates, METRES.

    Frame: X = chordwise, Y = out-of-plane (rotor axis), Z = spanwise.
    Order is scale -> shift to pitch axis -> twist -> prebend, and it matters:
    a real blade twists about its pitch axis, so the pitch-axis shift has to
    happen before the rotation, not after.
    """
    return apply_twist_prebend(station_points_local(rR, cfg), rR, cfg)


def surface_y_at(rR, cfg, x_frac):
    """Upper and lower surface y at a chordwise fraction, chord-normalised.

    Interpolates the ACTUAL section contour rather than assuming the surfaces
    sit at +/- half the maximum thickness about y = 0. That assumption is only
    true for a symmetric section; these are cambered, so the real surfaces are
    at (yc + yt) and (yc - yt), both shifted upward by the camber. Placing
    internal structure on the chord line instead of the camber line pushes the
    lower spar cap straight through the skin.
    """
    pts = blended_section(rR, cfg)
    m = (len(pts) + 1) // 2
    upper = [pts[m - 1 - k] for k in range(m)]     # LE -> TE
    lower = [pts[m - 1 + k] for k in range(m)]     # LE -> TE

    def interp(seq):
        for i in range(len(seq) - 1):
            x0, y0 = seq[i]
            x1, y1 = seq[i + 1]
            if (x0 - 1e-12) <= x_frac <= (x1 + 1e-12) and abs(x1 - x0) > 1e-12:
                f = (x_frac - x0) / (x1 - x0)
                return y0 + f * (y1 - y0)
        return seq[-1][1] if x_frac > seq[-1][0] else seq[0][1]

    return interp(upper), interp(lower)


def span_stations(cfg):
    """Span fractions for the loft sections.

    Clustered toward the root, where chord and thickness change fastest --
    uniform spacing there produces a visibly lumpy transition region.
    """
    n = cfg['n_stations']
    return [(i / (n - 1.0)) ** 1.25 for i in range(n)]


SKIN_CLEARANCE = 0.97   # fraction of the local half-depth the structure may use


def spar_cap_rect_local(rR, cfg, upper):
    """Spar-cap section at rR in the UNTWISTED frame, metres.

    A rectangle riding just inside the upper or lower skin, spanning the
    chordwise extent in CONFIG. The real cap follows the surface curvature; a
    rectangle of equivalent area is the standard first-order idealisation and
    is what a beam model of the blade assumes anyway.

    The inner surface is found from the ACTUAL contour at both chordwise ends
    (see surface_y_at) and the more restrictive of the two is used, so the cap
    stays inside the skin even where the section is strongly cambered.
    """
    c = chord_at(rR, cfg)
    ax = cfg['pitch_axis_frac']
    thk = cfg['spar_cap_thk_m']
    f0, f1 = cfg['spar_cap_start_frac'], cfg['spar_cap_end_frac']

    x0 = (f0 - ax) * c
    x1 = (f1 - ax) * c

    up0, lo0 = surface_y_at(rR, cfg, f0)
    up1, lo1 = surface_y_at(rR, cfg, f1)

    if upper:
        y_skin = min(up0, up1) * c * SKIN_CLEARANCE
        yo, yi = y_skin, y_skin - thk
    else:
        y_skin = max(lo0, lo1) * c * SKIN_CLEARANCE
        yo, yi = y_skin, y_skin + thk

    return [(x0, yo), (x1, yo), (x1, yi), (x0, yi)]


def shear_web_rect_local(rR, cfg, fore):
    """Shear web section at rR in the UNTWISTED frame, metres.

    Spans between the actual upper and lower surfaces at its chordwise
    station, again from the real contour rather than from +/- half thickness.
    """
    c = chord_at(rR, cfg)
    ax = cfg['pitch_axis_frac']
    thk = cfg['web_thk_m']

    frac = cfg['spar_cap_start_frac'] if fore else cfg['spar_cap_end_frac']
    xc = (frac - ax) * c
    x0, x1 = xc - 0.5 * thk, xc + 0.5 * thk

    # Sample the surface at BOTH edges of the web, not just its centreline,
    # and take the more restrictive value. Outboard the chord falls to ~1 m
    # while the web keeps its fixed 40 mm width, so the surface curves
    # appreciably across the web -- sampling only the centreline let the
    # corners protrude through the skin near the tip. The fore web sits close
    # to the leading edge, where curvature is highest, so it fails first.
    half_frac = 0.5 * thk / max(c, 1e-6)
    f0 = min(max(frac - half_frac, 0.0), 1.0)
    f1 = min(max(frac + half_frac, 0.0), 1.0)

    up0, lo0 = surface_y_at(rR, cfg, f0)
    up1, lo1 = surface_y_at(rR, cfg, f1)

    y_hi = min(up0, up1) * c * SKIN_CLEARANCE
    y_lo = max(lo0, lo1) * c * SKIN_CLEARANCE

    return [(x0, y_lo), (x1, y_lo), (x1, y_hi), (x0, y_hi)]


def spar_cap_rect(rR, cfg, upper):
    """Spar-cap section in blade coordinates, metres."""
    return apply_twist_prebend(spar_cap_rect_local(rR, cfg, upper), rR, cfg)


def shear_web_rect(rR, cfg, fore):
    """Shear web section in blade coordinates, metres."""
    return apply_twist_prebend(shear_web_rect_local(rR, cfg, fore), rR, cfg)


def blade_z_m(rR, cfg):
    """Spanwise position [m] from the rotor centre."""
    return cfg['hub_radius_m'] + rR * cfg['blade_length_m']


