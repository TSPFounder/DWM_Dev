# -*- coding: utf-8 -*-
"""
WindTurbineBlade.py — Autodesk Fusion script.

Builds the rotor assembly from Wind_Turbine_BOM.xlsx as parametric geometry:

    BOM 1100   Blade aeroshell   lofted through ~20 airfoil stations
    BOM 1110   Spar caps         upper and lower, lofted
    BOM 1120   Shear webs        fore and aft, lofted
    BOM 1200   Hub               revolved, with 3 blade flanges at 120 deg
    BOM 1400   Spinner           revolved ogive fairing
    BOM 1500   Root bolting      representative bolt circle

INSTALL AND RUN
---------------
1. Fusion -> Utilities tab -> ADD-INS -> Scripts and Add-Ins (or Shift+S)
2. Scripts -> the green "+" -> "Create New Script" (or point it at this folder)
3. Replace the generated .py with this file, keeping the folder and file names
   the same (Fusion requires MyScript/MyScript.py)
4. Select it -> Run

Everything is driven by CONFIG below. To change the blade, edit CONFIG and re-run.

TWO THINGS WORTH KNOWING BEFORE YOU RUN IT
------------------------------------------
1. FUSION'S INTERNAL UNIT IS THE CENTIMETRE, regardless of what the document
   is displaying. Every dimension in CONFIG is in METRES and is converted once,
   in M2CM. Getting this wrong is the classic Fusion API bug and it produces a
   blade 100x too small rather than an error.

2. "PARAMETRIC" HERE HAS A BOUNDARY. The hub, spinner and bolt circle are built
   from Fusion user parameters, so you can change those in the Parameters dialog
   and the model updates. The blade's lofted profiles CANNOT work that way --
   their spline points are computed by this script and baked into the sketches.
   To change blade chord, twist, thickness or prebend, edit CONFIG and re-run.
   Nothing in the Fusion API makes a swept airfoil loft driven by an equation.

WHAT THIS IS NOT
----------------
The airfoils are generated by the analytic NACA 4-digit formula, scaled to the
thickness distribution in the BOM. They are NOT the DU 00-W-401 / NACA 64-618
sections the BOM actually names -- those are 6-series and DU-series profiles
whose coordinates come from tabulated data, not a closed-form equation, and
inventing numbers for them would be worse than substituting an honest
placeholder. The result has the right planform, twist, thickness distribution
and prebend; the section shapes are representative.

To use the real sections: replace airfoil_section() with a lookup into your own
coordinate tables. That is the only function that needs to change -- everything
downstream consumes normalised (x/c, y/c) point lists.
"""

