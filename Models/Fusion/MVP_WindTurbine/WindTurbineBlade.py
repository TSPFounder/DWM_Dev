def _pt(x_m, y_m):
    """Point3D in a sketch, converting metres -> Fusion's centimetres."""
    return adsk.core.Point3D.create(x_m * M2CM, y_m * M2CM, 0.0)


def _offset_plane(comp, z_m):
    planes = comp.constructionPlanes
    pin = planes.createInput()
    pin.setByOffset(comp.xYConstructionPlane,
                    adsk.core.ValueInput.createByReal(z_m * M2CM))
    return planes.add(pin)


def _closed_profile_sketch(comp, z_m, pts_m, name):
    """Sketch a closed contour: fitted spline plus a straight closing segment.

    Returns the resulting Profile, or None if Fusion did not form one -- which
    happens if the contour self-intersects. Returning None rather than raising
    lets the caller skip one bad station and still loft the rest.
    """
    sk = comp.sketches.add(_offset_plane(comp, z_m))
    sk.name = name
    sk.isComputeDeferred = True        # large point sets are far faster this way

    col = adsk.core.ObjectCollection.create()
    for (x, y) in pts_m:
        col.add(_pt(x, y))
    sk.sketchCurves.sketchFittedSplines.add(col)

    # Close the blunt trailing edge with a line.
    sk.sketchCurves.sketchLines.addByTwoPoints(_pt(*pts_m[-1]), _pt(*pts_m[0]))

    sk.isComputeDeferred = False
    return sk.profiles.item(0) if sk.profiles.count > 0 else None


def _polygon_sketch(comp, z_m, pts_m, name):
    sk = comp.sketches.add(_offset_plane(comp, z_m))
    sk.name = name
    sk.isComputeDeferred = True
    lines = sk.sketchCurves.sketchLines
    n = len(pts_m)
    for i in range(n):
        lines.addByTwoPoints(_pt(*pts_m[i]), _pt(*pts_m[(i + 1) % n]))
    sk.isComputeDeferred = False
    return sk.profiles.item(0) if sk.profiles.count > 0 else None


def _loft(comp, profiles, name):
    if len(profiles) < 2:
        raise RuntimeError('%s: need at least 2 sections, got %d'
                           % (name, len(profiles)))
    lofts = comp.features.loftFeatures
    li = lofts.createInput(
        adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    for p in profiles:
        li.loftSections.add(p)
    li.isSolid = True
    feat = lofts.add(li)
    if feat.bodies.count > 0:
        feat.bodies.item(0).name = name
    return feat


def build_blade(parent, cfg, log):
    """Create the blade component: aeroshell, spar caps, shear webs."""
    occ = parent.occurrences.addNewComponent(adsk.core.Matrix3D.create())
    comp = occ.component
    comp.name = 'Blade'

    stations = span_stations(cfg)

    # ---- aeroshell, BOM 1100 ---------------------------------------------
    profiles = []
    skipped = []
    for i, rR in enumerate(stations):
        pts = station_points(rR, cfg)
        prof = _closed_profile_sketch(
            comp, blade_z_m(rR, cfg), pts, 'Station_%02d_r%.3f' % (i, rR))
        if prof is None:
            skipped.append(i)
        else:
            profiles.append(prof)

    if skipped:
        log.append('Aeroshell: %d station(s) produced no closed profile and '
                   'were skipped: %s' % (len(skipped), skipped))

    _loft(comp, profiles, 'Aeroshell')
    log.append('Aeroshell lofted through %d of %d stations.'
               % (len(profiles), len(stations)))

    # ---- internal structure, BOM 1110 / 1120 ------------------------------
    if cfg['build_structure']:
        r0, r1 = cfg['structure_root_frac'], cfg['structure_tip_frac']
        inner = [r for r in stations if r0 <= r <= r1]
        if len(inner) < 2:
            inner = [r0, r1]

        for upper in (True, False):
            nm = 'SparCap_%s' % ('Upper' if upper else 'Lower')
            profs = []
            for i, rR in enumerate(inner):
                p = _polygon_sketch(comp, blade_z_m(rR, cfg),
                                    spar_cap_rect(rR, cfg, upper),
                                    '%s_%02d' % (nm, i))
                if p:
                    profs.append(p)
            _loft(comp, profs, nm)
            log.append('%s lofted through %d sections.' % (nm, len(profs)))

        for fore in (True, False):
            nm = 'ShearWeb_%s' % ('Fore' if fore else 'Aft')
            profs = []
            for i, rR in enumerate(inner):
                p = _polygon_sketch(comp, blade_z_m(rR, cfg),
                                    shear_web_rect(rR, cfg, fore),
                                    '%s_%02d' % (nm, i))
                if p:
                    profs.append(p)
            _loft(comp, profs, nm)
            log.append('%s lofted through %d sections.' % (nm, len(profs)))

    return comp


def build_hub(parent, cfg, log):
    """Hub: revolved body with three blade flanges at 120 deg. BOM 1200."""
    occ = parent.occurrences.addNewComponent(adsk.core.Matrix3D.create())
    comp = occ.component
    comp.name = 'Hub'

    r = 0.5 * cfg['hub_envelope_dia_m'] * M2CM

    # Half-disc profile in XY, revolved about the Y axis -> sphere.
    sk = comp.sketches.add(comp.xYConstructionPlane)
    sk.name = 'HubProfile'
    p0 = adsk.core.Point3D.create(0.0, r, 0.0)
    p1 = adsk.core.Point3D.create(0.0, -r, 0.0)
    axis = sk.sketchCurves.sketchLines.addByTwoPoints(p0, p1)
    axis.isConstruction = True
    sk.sketchCurves.sketchArcs.addByThreePoints(
        p0, adsk.core.Point3D.create(r, 0.0, 0.0), p1)

    if sk.profiles.count == 0:
        raise RuntimeError('Hub: revolve profile did not close.')

    revs = comp.features.revolveFeatures
    ri = revs.createInput(
        sk.profiles.item(0), axis,
        adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    ri.setAngleExtent(False, adsk.core.ValueInput.createByReal(2.0 * math.pi))
    feat = revs.add(ri)
    if feat.bodies.count > 0:
        feat.bodies.item(0).name = 'HubCasting'

    # Three blade flanges, 120 deg apart about the rotor (Y) axis.
    fr = 0.5 * cfg['hub_flange_dia_m'] * M2CM
    fl = cfg['hub_flange_len_m'] * M2CM
    base = 0.5 * cfg['hub_envelope_dia_m'] * M2CM * 0.85

    for k in range(cfg['n_blades']):
        ang = 2.0 * math.pi * k / cfg['n_blades']
        pin = comp.constructionPlanes.createInput()
        pin.setByOffset(comp.xYConstructionPlane,
                        adsk.core.ValueInput.createByReal(base))
        pl = comp.constructionPlanes.add(pin)

        fsk = comp.sketches.add(pl)
        fsk.name = 'Flange_%d' % k
        fsk.sketchCurves.sketchCircles.addByCenterRadius(
            adsk.core.Point3D.create(0.0, 0.0, 0.0), fr)
        if fsk.profiles.count == 0:
            continue

        ext = comp.features.extrudeFeatures.addSimple(
            fsk.profiles.item(0),
            adsk.core.ValueInput.createByReal(fl),
            adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
        if ext.bodies.count > 0:
            b = ext.bodies.item(0)
            b.name = 'BladeFlange_%d' % k
            # Rotate this flange into position about the rotor axis.
            if abs(ang) > 1e-9:
                m = adsk.core.Matrix3D.create()
                m.setToRotation(ang, adsk.core.Vector3D.create(0, 1, 0),
                                adsk.core.Point3D.create(0, 0, 0))
                col = adsk.core.ObjectCollection.create()
                col.add(b)
                mi = comp.features.moveFeatures.createInput(col, m)
                comp.features.moveFeatures.add(mi)

    log.append('Hub built with %d blade flanges.' % cfg['n_blades'])
    return comp


def build_spinner(parent, cfg, log):
    """Spinner / nose cone: revolved ogive fairing. BOM 1400."""
    occ = parent.occurrences.addNewComponent(adsk.core.Matrix3D.create())
    comp = occ.component
    comp.name = 'Spinner'

    r = 0.5 * cfg['spinner_dia_m'] * M2CM
    L = cfg['spinner_len_m'] * M2CM

    sk = comp.sketches.add(comp.xYConstructionPlane)
    sk.name = 'SpinnerProfile'

    axis = sk.sketchCurves.sketchLines.addByTwoPoints(
        adsk.core.Point3D.create(0.0, -0.35 * L, 0.0),
        adsk.core.Point3D.create(0.0, L, 0.0))
    axis.isConstruction = True

    # Ogive: quarter-ellipse nose from tip to max radius.
    col = adsk.core.ObjectCollection.create()
    n = 24
    for i in range(n + 1):
        t = i / float(n)
        col.add(adsk.core.Point3D.create(r * math.sin(0.5 * math.pi * t),
                                         L * math.cos(0.5 * math.pi * t), 0.0))
    sk.sketchCurves.sketchFittedSplines.add(col)

    lines = sk.sketchCurves.sketchLines
    lines.addByTwoPoints(adsk.core.Point3D.create(r, 0.0, 0.0),
                         adsk.core.Point3D.create(r, -0.35 * L, 0.0))
    lines.addByTwoPoints(adsk.core.Point3D.create(r, -0.35 * L, 0.0),
                         adsk.core.Point3D.create(0.0, -0.35 * L, 0.0))
    lines.addByTwoPoints(adsk.core.Point3D.create(0.0, -0.35 * L, 0.0),
                         adsk.core.Point3D.create(0.0, L, 0.0))

    if sk.profiles.count == 0:
        raise RuntimeError('Spinner: revolve profile did not close.')

    revs = comp.features.revolveFeatures
    ri = revs.createInput(
        sk.profiles.item(0), axis,
        adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
    ri.setAngleExtent(False, adsk.core.ValueInput.createByReal(2.0 * math.pi))
    feat = revs.add(ri)
    if feat.bodies.count > 0:
        feat.bodies.item(0).name = 'SpinnerShell'

    log.append('Spinner built.')
    return comp


def build_root_bolts(parent, cfg, log):
    """Representative root bolt circle. BOM 1500.

    CONFIG uses a reduced bolt count on purpose -- the BOM specifies 80-120
    per blade, and modelling all of them triples rebuild time for a feature
    nobody inspects individually at assembly level. Raise bolt_count if you
    need the real pattern.
    """
    occ = parent.occurrences.addNewComponent(adsk.core.Matrix3D.create())
    comp = occ.component
    comp.name = 'RootBolts'

    bcr = 0.5 * cfg['bolt_circle_dia_m'] * M2CM
    br = 0.5 * cfg['bolt_dia_m'] * M2CM
    bl = cfg['bolt_len_m'] * M2CM
    z = cfg['hub_radius_m'] * M2CM

    pin = comp.constructionPlanes.createInput()
    pin.setByOffset(comp.xYConstructionPlane,
                    adsk.core.ValueInput.createByReal(z))
    pl = comp.constructionPlanes.add(pin)

    sk = comp.sketches.add(pl)
    sk.name = 'BoltCircle'
    sk.isComputeDeferred = True
    for k in range(cfg['bolt_count']):
        a = 2.0 * math.pi * k / cfg['bolt_count']
        sk.sketchCurves.sketchCircles.addByCenterRadius(
            adsk.core.Point3D.create(bcr * math.cos(a), bcr * math.sin(a), 0.0),
            br)
    sk.isComputeDeferred = False

    made = 0
    for i in range(sk.profiles.count):
        ext = comp.features.extrudeFeatures.addSimple(
            sk.profiles.item(i),
            adsk.core.ValueInput.createByReal(bl),
            adsk.fusion.FeatureOperations.NewBodyFeatureOperation)
        if ext.bodies.count > 0:
            ext.bodies.item(0).name = 'RootBolt_%02d' % i
            made += 1

    log.append('Root bolts: %d modelled (BOM specifies 80-120 -- reduced '
               'for rebuild time).' % made)
    return comp


def add_user_parameters(design, cfg, log):
    """Publish the non-lofted dimensions as Fusion user parameters.

    Only these are genuinely parametric after the script finishes. The blade
    loft is not -- see header note 2. Publishing the ones that ARE, and saying
    so, beats implying the whole model rebuilds from the Parameters dialog.
    """
    prm = design.userParameters
    wanted = [
        ('wt_hub_envelope_dia', cfg['hub_envelope_dia_m'], 'Hub envelope diameter, BOM 1200'),
        ('wt_hub_flange_dia',   cfg['hub_flange_dia_m'],   'Blade flange diameter, BOM 1200'),
        ('wt_spinner_dia',      cfg['spinner_dia_m'],      'Spinner diameter, BOM 1400'),
        ('wt_spinner_len',      cfg['spinner_len_m'],      'Spinner length, BOM 1400'),
        ('wt_bolt_circle_dia',  cfg['bolt_circle_dia_m'],  'Root bolt circle, BOM 1500'),
        ('wt_bolt_dia',         cfg['bolt_dia_m'],         'Root bolt diameter M36, BOM 1500'),
    ]
    added = 0
    for name, val_m, comment in wanted:
        if prm.itemByName(name) is not None:
            continue
        try:
            prm.add(name,
                    adsk.core.ValueInput.createByReal(val_m * M2CM),
                    'cm', comment)
            added += 1
        except Exception:
            pass
    log.append('User parameters published: %d' % added)


